"""Re-score recorded blind round-trip answers with every official English source of a form.

    uv run python scripts/rescore_accepted_sources.py --freeze   # needs git history (writes the snapshot)
    uv run python scripts/rescore_accepted_sources.py --run      # replays the immutable judges

Only pt (#171) scored a form against all of its official English sources; the other
languages were scored against the first ``from`` only. ``--freeze`` writes
``roundtrip_judge/accepted_sources_v1.json``: for every non-pt v4 record, the measured
source(s) of its latest cohort plus every English ``from`` that a bank on main mapped to
that exact (lang, form) as its adopted winner, at the measurement bases and current main
(SNAPSHOTS). pt keeps its frozen ``pt_sources.json`` (#171, same rule at cdb8953).

``--run`` replays the existing ``roundtrip_judge/<lang>_blind.json`` answers through
``roundtrip.run()`` with those accepted sources and the owner-approved
``leading-que-that-v1`` marker equivalence. No new judging; run() owns every count; the
target identities (first source, converted prompt, seed) are the measured ones, so the
previous cohort stays in the history and the new cohort is appended.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import re
import subprocess
from pathlib import Path

import roundtrip as rt

ROOT = Path(__file__).resolve().parents[1]
FIX = ROOT / "SentenceCalibratedMosaic/fixtures/roundtrip_judge"
SNAPSHOT_PATH = FIX / "accepted_sources_v1.json"
BANKS = ("tense_matrix", "es_fr_tense", "pt_el_latin_tense", "pt_el_latin_phrases", "zh_de_phrases")
# measurement bases: it / nl / zh 84e5dca, es / fr / de / pt cdb8953, cs / pl b722a8c,
# el a2f5dd1, la 1602fce, plus main at the time of this re-score.
SNAPSHOTS = ("84e5dca0028d90db73254af33ac2d9d3ce545790", "cdb895387170d42990ebf93573a307959b92c148",
             "b722a8cb7819864629b683cbff3c3283f31fea91", "a2f5dd10646d4ee1f8e96c9936990d76362c4457",
             "1602fce384de5dc434b2592f70ed100ab7398f69", "2e5312adc25c445685994aa03211804bd1d7ef4a")
LANG_ORDER = ("nl", "es", "it", "zh", "fr", "cs", "pl", "el", "de", "la", "pt")
RESCORE_NOTE = ("Re-score only (no new judging): recorded answers of the same immutable judge replayed with "
                "every official English source of the form (any-official-source-v1) and the owner-approved "
                "leading-que-that-v1 marker equivalence (scripts/rescore_accepted_sources.py).")


def _git_json(commit: str, name: str) -> dict:
    for root in ("SentenceCalibratedMosaic", "TesseraTalk"):
        try:
            raw = subprocess.check_output(["git", "-C", str(ROOT), "show", f"{commit}:{root}/fixtures/{name}.json"],
                                          stderr=subprocess.DEVNULL)
        except subprocess.CalledProcessError:
            continue
        return json.loads(raw)
    raise FileNotFoundError(f"{commit}:{name}")


def _measured_sources(data: dict, rec: dict) -> list[str]:
    """First sources of the latest cohort, recovered from the mid-sentence template."""
    out = []
    for t in rt.latest_cohort(rec)["targets"]:
        m = re.fullmatch(r"Maybe (.+) today\.", t["source"])
        if m and m.group(1) not in out:
            out.append(m.group(1))
    for s in out:  # every recorded target must be regenerated by these sources
        assert any((t["source"], t["converted"]) in rt.sentences(data, s, rec["form"])
                   for t in rt.latest_cohort(rec)["targets"]), (rec["form"], s)
    regenerated = {pair for s in out for pair in rt.sentences(data, s, rec["form"])}
    assert {(t["source"], t["converted"]) for t in rt.latest_cohort(rec)["targets"]} == regenerated, rec["form"]
    return out


def freeze(data: dict) -> dict:
    official: dict[tuple[str, str], dict[tuple, list]] = {}
    for commit in SNAPSHOTS:
        for bank in BANKS:
            for e in _git_json(commit, bank)["entries"]:
                if e.get("lang") and e.get("to") and e["to"] != e["from"][0]:
                    seen = official.setdefault((e["lang"], e["to"]), {}).setdefault(tuple(e["from"]), [])
                    if [commit, bank, e["id"]] not in seen:
                        seen.append([commit, bank, e["id"]])
    forms = {}
    for key, rec in data["records"].items():
        if rec.get("accounting_version") != 4 or rec["lang"] == "pt" or rt.latest_cohort(rec) is None:
            continue
        measured = _measured_sources(data, rec)
        found = official.get((rec["lang"], rec["form"]), {})
        accepted = list(dict.fromkeys(measured + [s for fr in found for s in fr]))
        forms[key] = {"lang": rec["lang"], "form": rec["form"], "measured_sources": measured,
                      "accepted_sources": accepted,
                      "official": [{"from": list(fr), "seen": seen} for fr, seen in found.items()]}
    return {"version": 1, "snapshots": list(SNAPSHOTS), "banks": list(BANKS),
            "rule": "accepted = measured first source(s) + every English `from` of a bank entry whose adopted (lang, to) is exactly this form, on any snapshot; candidates that did not win are not official",
            "forms": forms}


def _plan(data: dict, snapshot: dict) -> dict[str, dict]:
    plan: dict[str, dict] = {}
    for key, f in snapshot["forms"].items():
        plan.setdefault(f["lang"], {"entries": [], "accepted": {}})
        for s in f["measured_sources"]:
            plan[f["lang"]]["entries"].append({"lang": f["lang"], "from": [s], "to": f["form"]})
        plan[f["lang"]]["accepted"][key] = f["accepted_sources"]
    pt = json.loads((FIX / "pt_sources.json").read_text(encoding="utf-8"))["forms"]
    plan["pt"] = {"entries": [f["entry"] for f in pt], "accepted": {f["key"]: f["accepted_sources"] for f in pt}}
    return plan


def measure(data: dict) -> dict:
    snapshot = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))
    plan = _plan(data, snapshot)
    for lang in LANG_ORDER:
        p = plan[lang]
        keys = list(p["accepted"])
        previous = {k: rt.latest_cohort(data["records"][k]) for k in keys}
        configs = {(c["config"]["command_sha256"], c["config"].get("only_lang")) for c in previous.values()}
        if len(configs) != 1:
            raise ValueError(f"{lang}: cohorts were not recorded by one replay command")
        (command_sha, only_lang), = configs
        cmd = f"uv run python scripts/roundtrip_replay.py {lang}"
        if hashlib.sha256(cmd.encode("utf-8")).hexdigest() != command_sha:
            raise ValueError(f"{lang}: replay command differs from the recorded one")
        rt.run(data, cmd, only_lang=only_lang, entries=p["entries"], accepted_sources=p["accepted"],
               marker_equivalence=rt.MARKER_EQUIVALENCE)
        latest = data["run_history"][-1]
        if not latest["complete"] or not latest["verifiable"] or latest["duplicate_targets"]:
            raise RuntimeError(f"{lang}: incomplete re-score")
        for k in keys:
            cohort = data["records"][k]["cohorts"][-1]
            old = previous[k]
            if {t["target_id"] for t in cohort["targets"]} != {t["target_id"] for t in old["targets"]}:
                raise RuntimeError(f"{k}: re-score changed the measured targets")
            if any(t["first_source_match"] != next(o for o in old["targets"] if o["target_id"] == t["target_id"]).get(
                    "first_source_match", next(o for o in old["targets"] if o["target_id"] == t["target_id"])["restored"])
                   for t in cohort["targets"]):
                raise RuntimeError(f"{k}: replay does not reproduce the recorded first-source result")
            prov = copy.deepcopy(old.get("judge_provenance") or {"kind": "recorded_blind_judge"})
            prov["rescore"] = {"of_run_id": old["run_id"], "note": RESCORE_NOTE,
                               "accepted_sources_file": "SentenceCalibratedMosaic/fixtures/roundtrip_judge/accepted_sources_v1.json"
                               if lang != "pt" else "SentenceCalibratedMosaic/fixtures/roundtrip_judge/pt_sources.json"}
            cohort["judge_provenance"] = prov
        latest["rescore_of"] = sorted({previous[k]["run_id"] for k in keys})
    return data


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--freeze", action="store_true")
    mode.add_argument("--run", action="store_true")
    a = ap.parse_args()
    data = rt.load()
    if a.freeze:
        SNAPSHOT_PATH.write_text(json.dumps(freeze(data), ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        return
    rt.DATA_PATH.write_text(json.dumps(measure(data), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
