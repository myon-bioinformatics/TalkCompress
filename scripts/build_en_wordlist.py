"""Build ``TesseraTalk/fixtures/en_wordlist.txt`` (English homograph guard lexicon).

Source: Hunspell ``en_US.dic`` (SCOWL-derived; LibreOffice/dictionaries
``en/en_US.dic``). Stdlib only, deterministic::

    python scripts/build_en_wordlist.py path/to/en_US.dic

Keeps lowercase ASCII entries (proper nouns / abbreviations with capitals,
apostrophes and digits dropped), expands only the regular inflection flags
S (plural / 3sg -s), D (-ed) and G (-ing) (not on letter names, so no ``es``),
keeps single letters only for the real words ``a`` / ``i`` and adds a few
closed-class words the .dic omits or only derives via letter plurals.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "TesseraTalk/fixtures/en_wordlist.txt"

HEADER = """\
# English wordlist for the B-final homograph guard (TesseraTalk tense banks).
# Generated by scripts/build_en_wordlist.py from Hunspell en_US.dic
# (SCOWL-derived, via LibreOffice/dictionaries en/en_US.dic): lowercase ASCII
# words + regular S/D/G inflections. One word per line, sorted.
#
# Copyright 2000-2026 by Kevin Atkinson.
# Permission to use, copy, modify, distribute, and sell any part of the
# English Speller Database (ESDB, previously known as SCOWLv2), or word lists
# created from it, is hereby granted without fee, provided that the above
# copyright notice appears in all copies and that both the above copyright
# notice and this notice appear in supporting documentation. Kevin Atkinson
# makes no representations about the suitability of this database for any
# purpose. It is provided "as is" without express or implied warranty.
"""

EXTRA = ("as", "has", "her", "into", "is", "only", "us")
SINGLE_OK = {"a", "i"}


def _s(w: str) -> str:
    if re.search(r"[^aeiou]y$", w):
        return w[:-1] + "ies"
    if re.search(r"(s|x|z|ch|sh)$", w):
        return w + "es"
    return w + "s"


def _d(w: str) -> str:
    if w.endswith("e"):
        return w + "d"
    if re.search(r"[^aeiou]y$", w):
        return w[:-1] + "ied"
    return w + "ed"


def _g(w: str) -> str:
    if w.endswith("e") and not w.endswith("ee"):
        return w[:-1] + "ing"
    return w + "ing"


def build(dic_text: str) -> str:
    words: set[str] = set(EXTRA)
    lines = dic_text.splitlines()
    if lines and lines[0].strip().isdigit():
        lines = lines[1:]
    for ln in lines:
        w, _, flags = ln.strip().partition("/")
        if not re.fullmatch(r"[a-z]+", w):
            continue
        forms = {w}
        if len(w) == 1:  # letter names: no plurals (es, os …), keep a / i only
            flags = ""
        if "S" in flags:
            forms.add(_s(w))
        if "D" in flags:
            forms.add(_d(w))
        if "G" in flags:
            forms.add(_g(w))
        words |= {f for f in forms if len(f) > 1 or f in SINGLE_OK}
    return HEADER + "\n".join(sorted(words)) + "\n"


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        raise SystemExit(__doc__)
    OUT.write_text(build(Path(argv[0]).read_text(encoding="utf-8")), encoding="utf-8")
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
